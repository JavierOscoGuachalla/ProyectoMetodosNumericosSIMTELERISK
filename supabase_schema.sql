-- =====================================================================
-- SIMTELE-RISK · Esquema PostgreSQL para Supabase
-- Ejecutar completo en: Supabase → SQL Editor → New query → Run.
-- Es idempotente: se puede volver a ejecutar sin perder datos.
-- Seis tablas: caso_estudio, escenario, simulacion, ejecucion_metodo,
--              iteracion_resultado, resultado_resumen
-- Seguridad: RLS activado en todas. Lectura pública; escritura solo para
--            usuarios autenticados y únicamente sobre sus propios registros.
-- =====================================================================

-- ---------- Tablas ----------
create table if not exists public.caso_estudio (
  id             bigint generated by default as identity primary key,
  nombre         text not null unique,
  modelo_version text not null default '1.0'
);

create table if not exists public.escenario (
  id              bigint generated by default as identity primary key,
  caso_id         bigint not null references public.caso_estudio(id) on delete cascade,
  tipo            text   not null check (tipo in ('NORMAL','ESTRES','MAL_CONDICIONADO')),
  parametros_json jsonb  not null,
  fuente_datos    text   not null default 'supuesto del equipo',
  usuario_id      uuid   not null default auth.uid() references auth.users(id) on delete cascade
);

create table if not exists public.simulacion (
  id           bigint generated by default as identity primary key,
  escenario_id bigint not null references public.escenario(id) on delete cascade,
  nombre       text   not null,
  notas        text,
  fecha        timestamptz not null default now(),
  equipo       text,
  estado       text   not null default 'PENDIENTE' check (estado in ('PENDIENTE','COMPLETA','ERROR')),
  usuario_id   uuid   not null default auth.uid() references auth.users(id) on delete cascade
);

create table if not exists public.ejecucion_metodo (
  id            bigint generated by default as identity primary key,
  simulacion_id bigint not null references public.simulacion(id) on delete cascade,
  metodo        text   not null,
  tolerancia    double precision,
  paso          double precision,
  max_iter      integer,
  convergio     boolean not null,
  tiempo_ms     double precision
);

create table if not exists public.iteracion_resultado (
  id                bigint generated by default as identity primary key,
  ejecucion_id      bigint not null references public.ejecucion_metodo(id) on delete cascade,
  numero            integer not null,
  aproximacion_json jsonb   not null,
  residual          double precision,
  error_abs         double precision,
  error_rel         double precision
);

create table if not exists public.resultado_resumen (
  id                 bigint generated by default as identity primary key,
  ejecucion_id       bigint not null references public.ejecucion_metodo(id) on delete cascade,
  referencia         text,
  valor_json         jsonb,
  metrica_error_json jsonb,
  interpretacion     text
);

-- ---------- Índices (los 4 originales + índices de apoyo para RLS) ----------
create index if not exists idx_esc_caso   on public.escenario(caso_id);
create index if not exists idx_sim_esc    on public.simulacion(escenario_id);
create index if not exists idx_ej_sim     on public.ejecucion_metodo(simulacion_id);
create index if not exists idx_it_ej      on public.iteracion_resultado(ejecucion_id);
create index if not exists idx_res_ej     on public.resultado_resumen(ejecucion_id);
create index if not exists idx_esc_user   on public.escenario(usuario_id);
create index if not exists idx_sim_user   on public.simulacion(usuario_id);

-- ---------- Datos iniciales ----------
insert into public.caso_estudio (id, nombre) overriding system value
values (1,'Detención'), (2,'Deterioro'), (3,'Oscilaciones'), (4,'Sensores')
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.caso_estudio','id'), greatest((select max(id) from public.caso_estudio), 4));

-- ---------- Privilegios: anon solo lectura; authenticated escribe (limitado por RLS) ----------
revoke all on public.caso_estudio, public.escenario, public.simulacion, public.ejecucion_metodo,
              public.iteracion_resultado, public.resultado_resumen from anon, authenticated;
grant select on public.caso_estudio, public.escenario, public.simulacion, public.ejecucion_metodo,
                public.iteracion_resultado, public.resultado_resumen to anon, authenticated;
grant insert, update, delete on public.escenario, public.simulacion, public.ejecucion_metodo,
                                public.iteracion_resultado, public.resultado_resumen to authenticated;

-- ---------- Row Level Security ----------
alter table public.caso_estudio        enable row level security;
alter table public.escenario           enable row level security;
alter table public.simulacion          enable row level security;
alter table public.ejecucion_metodo    enable row level security;
alter table public.iteracion_resultado enable row level security;
alter table public.resultado_resumen   enable row level security;

-- Lectura pública (para que cualquiera vea los resultados desde GitHub Pages).
-- Si prefieres que cada usuario solo vea lo suyo, cambia "using (true)" por
-- "using (usuario_id = (select auth.uid()))" en escenario y simulacion
-- y usa el mismo EXISTS de las políticas de escritura en las demás tablas.
drop policy if exists "lectura publica" on public.caso_estudio;
create policy "lectura publica" on public.caso_estudio for select to anon, authenticated using (true);
-- caso_estudio: sin políticas de escritura => nadie puede modificarla desde la API.

-- escenario
drop policy if exists "lectura publica" on public.escenario;
drop policy if exists "propietario inserta" on public.escenario;
drop policy if exists "propietario actualiza" on public.escenario;
drop policy if exists "propietario elimina" on public.escenario;
create policy "lectura publica"      on public.escenario for select to anon, authenticated using (true);
create policy "propietario inserta"  on public.escenario for insert to authenticated with check (usuario_id = (select auth.uid()));
create policy "propietario actualiza" on public.escenario for update to authenticated
  using (usuario_id = (select auth.uid())) with check (usuario_id = (select auth.uid()));
create policy "propietario elimina"  on public.escenario for delete to authenticated using (usuario_id = (select auth.uid()));

-- simulacion (además, el escenario referenciado debe ser del mismo usuario)
drop policy if exists "lectura publica" on public.simulacion;
drop policy if exists "propietario inserta" on public.simulacion;
drop policy if exists "propietario actualiza" on public.simulacion;
drop policy if exists "propietario elimina" on public.simulacion;
create policy "lectura publica"      on public.simulacion for select to anon, authenticated using (true);
create policy "propietario inserta"  on public.simulacion for insert to authenticated
  with check (usuario_id = (select auth.uid())
              and exists (select 1 from public.escenario e where e.id = escenario_id and e.usuario_id = (select auth.uid())));
create policy "propietario actualiza" on public.simulacion for update to authenticated
  using (usuario_id = (select auth.uid())) with check (usuario_id = (select auth.uid()));
create policy "propietario elimina"  on public.simulacion for delete to authenticated using (usuario_id = (select auth.uid()));

-- ejecucion_metodo (propietario = dueño de la simulación)
drop policy if exists "lectura publica" on public.ejecucion_metodo;
drop policy if exists "propietario escribe" on public.ejecucion_metodo;
create policy "lectura publica" on public.ejecucion_metodo for select to anon, authenticated using (true);
create policy "propietario escribe" on public.ejecucion_metodo for all to authenticated
  using      (exists (select 1 from public.simulacion s where s.id = simulacion_id and s.usuario_id = (select auth.uid())))
  with check (exists (select 1 from public.simulacion s where s.id = simulacion_id and s.usuario_id = (select auth.uid())));

-- iteracion_resultado (propietario = dueño de la simulación de la ejecución)
drop policy if exists "lectura publica" on public.iteracion_resultado;
drop policy if exists "propietario escribe" on public.iteracion_resultado;
create policy "lectura publica" on public.iteracion_resultado for select to anon, authenticated using (true);
create policy "propietario escribe" on public.iteracion_resultado for all to authenticated
  using      (exists (select 1 from public.ejecucion_metodo m join public.simulacion s on s.id = m.simulacion_id
                      where m.id = ejecucion_id and s.usuario_id = (select auth.uid())))
  with check (exists (select 1 from public.ejecucion_metodo m join public.simulacion s on s.id = m.simulacion_id
                      where m.id = ejecucion_id and s.usuario_id = (select auth.uid())));

-- resultado_resumen (igual que iteracion_resultado)
drop policy if exists "lectura publica" on public.resultado_resumen;
drop policy if exists "propietario escribe" on public.resultado_resumen;
create policy "lectura publica" on public.resultado_resumen for select to anon, authenticated using (true);
create policy "propietario escribe" on public.resultado_resumen for all to authenticated
  using      (exists (select 1 from public.ejecucion_metodo m join public.simulacion s on s.id = m.simulacion_id
                      where m.id = ejecucion_id and s.usuario_id = (select auth.uid())))
  with check (exists (select 1 from public.ejecucion_metodo m join public.simulacion s on s.id = m.simulacion_id
                      where m.id = ejecucion_id and s.usuario_id = (select auth.uid())));
